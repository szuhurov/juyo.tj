/** Probability-like score in [0, 1]; null when the vector is from another model. */
export function documentScore(model: string, vector: ArrayLike<number>): number | null {
  if (model !== DOCUMENT_HEAD_MODEL || vector.length !== WEIGHTS.length) return null;
  let z = BIAS;
  for (let i = 0; i < WEIGHTS.length; i++) z += WEIGHTS[i] * vector[i];
  return 1 / (1 + Math.exp(-z));
}

export function looksLikeDocument(model: string, vector: ArrayLike<number>): boolean {
  const s = documentScore(model, vector);
  return s != null && s >= DOCUMENT_HEAD_THRESHOLD;
}
