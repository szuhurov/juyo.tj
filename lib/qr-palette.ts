/** `#RGB` ё `#RRGGBB` → [r, g, b] дар 0…255. */
function toRgb(hex: string): [number, number, number] {
  let h = hex.replace('#', '').trim();
  if (h.length === 3) h = h[0] + h[0] + h[1] + h[1] + h[2] + h[2];
  const n = parseInt(h, 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
}

/** Дурахшонии нисбӣ аз рӯи WCAG. */
function luminance(hex: string): number {
  const [r, g, b] = toRgb(hex).map((v) => {
    const x = v / 255;
    return x <= 0.03928 ? x / 12.92 : ((x + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

/**
 * Фарқи дурахшонии ду ранг: 0 (якхела) … 1 (сиёҳ ва сафед).
 *
 * ҚАСДАН на таносуби контрасти WCAG.
 *
 * WCAG барои ХОНДАНИ МАТН аз ҷониби ОДАМ сохта шудааст ва рангҳои
 * равшанро сахт ҷазо медиҳад. Скани QR масъалаи дигар аст: камера
 * фарқи ИНЪИКОС-ро мебинад, ва ISO 18004 маҳз онро — на камтар аз
 * 40% — талаб мекунад.
 *
 * Фарқ дар амал ҳам дида мешавад. Ҷуфти пешфарзи JUYO
 * (`#26BA90` / `#EEFBF5`) аз рӯи WCAG ҳамагӣ 2.32:1 медиҳад — яъне
 * «бад» ба ҳисоб мерафт, дар ҳоле ки он солҳо боз бе мушкил скан
 * мешавад. Аз рӯи фарқи дурахшонӣ он 0.56 аст — хеле боло аз ҳад.
 */
export function luminanceDelta(a: string, b: string): number {
  return Math.abs(luminance(a) - luminance(b));
}

/**
 * Ранги матн, ки дар болои ранги додашуда хонда мешавад.
 *
 * Ҳамон ҳисоби дурахшонӣ: заминаи торик → матни сафед, равшан → сиёҳ.
 * Ин барои тугмаҳои рангпуршуда лозим аст — ранги матни СОБИТ дар нисфи
 * ҳолатҳо нохоно мешуд.
 */
export function readableTextOn(hex: string): string {
  return luminance(hex) > 0.45 ? '#111827' : '#FFFFFF';
}

/**
 * Ҳадди поёнӣ — ҳамон 40%-и ISO 18004.
 *
 * Дар санҷиш ин ҷуфтҳои бадро аниқ ҷудо мекунад:
 *
 *     пешфарзи JUYO   0.56  ✓
 *     сиёҳ / сафед    0.99  ✓
 *     сабз / сабз     0.18  ✗
 *     хокистарӣ       0.30  ✗
 *     зард / сафед    0.25  ✗
 */
export const MIN_QR_LUMINANCE_DELTA = 0.4;

/**
 * Оё ин ҷуфт барои скан кофист?
 *
 * Ин на масъалаи зебоӣ аст: корбар метавонад стикери сканнашавандаро
 * ЧОП кунад ва танҳо баъд аз часпондан ба ашё бифаҳмад.
 */
export function isScannablePair(qr: string, bg: string): boolean {
  return luminanceDelta(qr, bg) >= MIN_QR_LUMINANCE_DELTA;
}

/**
 * Оё ранг ба сафед хеле наздик аст?
 *
 * Барои доира/лавҳачаҳои интихоби ранг: агар ранг тамоман сафед (ё қариб
 * сафед) бошад, он дар заминаи сафеди корт бе хат гум мешавад. Хат
 * ФАҚАТ дар ин ҳолат лозим аст — барои рангҳои дигар зиёдатист.
 */
export function isNearWhite(hex: string): boolean {
  return luminance(hex) > 0.9;
}
