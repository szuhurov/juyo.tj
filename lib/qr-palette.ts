/**
 * Кунҷи дараҷа → ду нуқтаи градиент дар фазои 0..1.
 *
 * y дар SVG ба ПОЁН меафзояд, пас 45° ранги якумро ба боло-чап ва дуюмро
 * ба поён-рост мегузорад. Афзоиши кунҷ — давр задани АҚРАБАКИ СОАТ.
 *
 * Ин ҷо мемонад, на дар `QrDesignCard`: ҳам стикер, ҳам намунаҳои интихоб
 * бояд айнан як ҳисобро истифода баранд, вагарна намуна чизеро нишон
 * медиҳад, ки QR онро надорад.
 */
export function gradientPoints(deg: number, bias = 1) {
  const rad = (deg * Math.PI) / 180;
  const dx = Math.cos(rad) / 2;
  const dy = Math.sin(rad) / 2;
  // Нуқтаи оғоз аз чорчӯба БЕРУН бароварда мешавад: он гоҳ дохили QR
  // гузариш аллакай оғозшуда дида мешавад ва ранги якум ҷои камтар
  // мегирад. Нуқтаи охир даст намехӯрад, вагарна ранги дуюм низ бурида
  // мешуд.
  return {
    start: [0.5 - dx * bias, 0.5 - dy * bias] as [number, number],
    end: [0.5 + dx, 0.5 + dy] as [number, number],
  };
}

/**
 * Ҳар ҷуфт ЧОР маротиба меояд — бо як ранг, вале давр задашуда.
 *
 * Ҳар қадам 90° аз рӯи ақрабаки соат: ранги якум аз як кунҷ ба кунҷи
 * дигар мегузарад ва баъд аз чор қадам ба ҷои худ бармегардад. Ин
 * рӯйхатро аз 7 то 28 мерасонад, бе он ки ягон ранги нав пайдо шавад —
 * ҳамон ҷуфтҳои санҷидашуда, танҳо самти дигар.
 */
export const QR_GRADIENTS: QrGradient[] = QR_GRADIENT_BASE.flatMap((g) =>
  [0, 90, 180, 270].map((turn) => ({ ...g, angle: (g.angle + turn) % 360 })),
);

