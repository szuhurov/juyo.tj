/**
 * Ҷуфтҳои тайёри ранг ва санҷиши контрасти QR.
 *
 * Ду сабаб барои ҷуфт, на ду ранги алоҳида:
 *
 *   1. Корбар аслан намехоҳад hex интихоб кунад — ӯ мехоҳад «зебо
 *      шавад». Ҷуфти тайёр ин корро як ламс мекунад.
 *   2. Ду ранги тасодуфӣ метавонанд QR-ро СКАННАШАВАНДА кунанд. Ҷуфтҳои
 *      ин ҷо ҳамаашон санҷида шудаанд.
 */

export type QrPair = { qr: string; bg: string };

/**
 * Градиентҳои ТАЙЁР барои нуқтаҳои QR.
 *
 * Чаро рӯйхат, на интихоби дастии ду ранг + кунҷ: ҷуфти тасодуфӣ
 * метавонад QR-ро сканнашаванда кунад, ва корбар инро танҳо баъд аз
 * ЧОП кардани стикер мефаҳмад. Ҳар ҷуфти ин ҷо аз санҷиши
 * `isScannablePair` мегузарад — ҲАРДУ нуқтаи он.
 *
 * Ҳар ҷуфт аз ДУ санҷиш мегузарад:
 *
 *   1. `isScannablePair` — ҳарду нуқта дар заминаи равшан хонда шаванд.
 *   2. фарқи тобиши на камтар аз 70°.
 *
 * Шарти дуюм баъдтар илова шуд. Бе он рӯйхат ҷуфтҳое дошт, ки градиент
 * будани онҳо тамоман дида намешуд: `#111827 → #4B5563` ҳамагӣ 6° фарқ
 * дошт, `#065F46 → #166534` — 20°. Онҳо ба чашм якранг менамуданд.
 *
 * Тартиб ДАСТӢ аст — он аз рӯи фарқи тобиш чида шуда буд, вале баъдтар
 * корбар худаш онро аз рӯи зебоӣ аз нав чид. Якум пешфарзи Pro мешавад.
 *
 * Кунҷ ба ҳар ҷуфт часпидааст: 45° барои аксарият табиист, вале
 * ҷуфтҳои амудӣ (135°) диданашон беҳтар аст.
 */
export type QrGradient = {
  from: string;
  to: string;
  angle: number;
  /**
   * Тақсими ҷои ду ранг. 1 = баробари риёзӣ, >1 ба ранги ДУЮМ ҷои
   * бештар, <1 ба ранги ЯКУМ.
   *
   * Лозим аст, чунки баробарии риёзӣ баробарии ЧАШМ нест: омехтаи мобайн
   * тобиши сеюм месозад ва он ба яке аз ду канор наздиктар дида мешавад —
   * ҳамон канор ҷои бештар мегирад. Дар ин рӯйхат бунафши равшан қариб
   * ҳамеша ғолиб мебарояд.
   *
   * Қиматҳо бо ЧАШМ чида шудаанд, на бо формула: ду модел (масофаи LAB
   * то мобайн ва тобиш) санҷида шуданд ва ҳеҷ кадоме натиҷаи дидашударо
   * такрор накард — барои ҷуфти якум онҳо 1.08 ва 1.22 медоданд, дар
   * ҳоле ки воқеан 1.7 лозим буд.
   */
  bias?: number;
  /**
   * Кадом канор ба қисмҳои ЯКРАНГ ранг медиҳад — чашмакҳои кунҷ, JUYO
   * ва матни поён. Пешфарз `from`.
   *
   * Онҳо аз градиент берунанд ва як ранги қатъӣ мехоҳанд. Гирифтани
   * ҳамеша `from` бад аст: ҳангоми `bias` > 1 ранги `from`-и соф дар
   * худи QR умуман вуҷуд надорад, пас чашмакҳо ранге мегиранд, ки дар
   * тасвир нест.
   */
  accent?: 'from' | 'to';
};

