-- Бартараф кардани `secondary_phone_type`.
--
-- Ин сутун навъи соҳиби рақами эҳтиётиро нигоҳ медошт (падар / модар /
-- бародар / хоҳар / ҳамсар) ва ҳангоми боргирии QR интихоби он ҲАТМӢ буд.
-- Талаби корбар: он тамоман бардошта шавад — ҳам аз интерфейс, ҳам аз
-- пойгоҳи додаҳо. Акнун танҳо худи рақами иловагӣ пурсида мешавад.
--
-- ⚠ ЭҲТИЁТ: ин амал маълумоти мавҷударо БЕБОЗГАШТ нест мекунад. Дар
-- ҷадвал сатрҳое ҳастанд, ки ин сутун пур аст. Пеш аз иҷро нусхабардорӣ
-- кунед, агар он маълумот ба шумо лозим бошад:
--
--   select id, secondary_phone, secondary_phone_type
--   from public.profiles
--   where secondary_phone_type is not null;
--
-- Коди барнома аллакай ин сутунро на менависад ва на мехонад, бинобар ин
-- миграцияро ҳар вақт иҷро кардан мумкин аст — шитоб лозим нест.

alter table public.profiles
  drop column if exists secondary_phone_type;
